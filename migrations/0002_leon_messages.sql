CREATE TABLE leon_messages (
  id INTEGER PRIMARY KEY,
  message TEXT NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT TRUE CHECK (active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE leon_message_history (
  shown_on TEXT PRIMARY KEY,
  message_id INTEGER NOT NULL REFERENCES leon_messages(id),
  selected_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_leon_message_history_message
ON leon_message_history(message_id);

